def wrap(text, width):
    lines, cur = [], ''
    for w in text.split():
        if not cur: cur = w
        elif len(cur) + 1 + len(w) <= width: cur += ' ' + w
        else: lines.append(cur); cur = w
    if cur: lines.append(cur)
    return lines

def lines():
    out = [''] * 135
    for name, first, n, text in SECTIONS:
        for width in range(28, 39):              # narrowest width that still fits: fills the section evenly
            L = wrap(text, width)
            if len(L) <= n: break
        assert len(L) <= n, (name, len(L), n)
        L += [''] * (n - len(L))
        out[first:first + n] = L
    return out

